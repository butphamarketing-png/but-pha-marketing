/**
 * Parse tmp-programmatic/nganh-nghe-500.md → keyword + industry entries.
 * Chạy: node scripts/_gen-niche-500.mjs
 */
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const mdPath = path.join(root, "tmp-programmatic", "nganh-nghe-500.md");
const outKw = path.join(root, "scripts", "seo-niche-500-keywords.mjs");
const outInd = path.join(root, "scripts", "seo-niche-500-industry.mjs");
const industryDataPath = path.join(root, "scripts", "seo-industry-data.mjs");

/** Không import module (tránh circular sau khi wire niche vào INDUSTRY_ENTRIES). */
const industrySrc = fs.readFileSync(industryDataPath, "utf8");
const existing = new Set(
  [...industrySrc.matchAll(/slug:\s*"([^"]+)"/g)].map((m) => m[1]).filter((s) => s.startsWith("thiet-ke-website-")),
);
const text = fs.readFileSync(mdPath, "utf8");
const lineRe = /^\d+\.\s+(.+?)\s+—\s+`([^`]+)`\s*$/gm;

const niches = [];
const seenSlug = new Set();
for (const m of text.matchAll(lineRe)) {
  const label = m[1].replace(/\s+/g, " ").trim();
  let token = m[2].trim().toLowerCase();
  if (seenSlug.has(token)) token = `${token}-v2`;
  seenSlug.add(token);
  const slug = `thiet-ke-website-${token}`;
  niches.push({ label, token, slug });
}

function titleCaseVi(s) {
  return s
    .split(" ")
    .map((w) => (w ? w[0].toUpperCase() + w.slice(1) : w))
    .join(" ");
}

const keywords = [];
const industries = [];
let skippedExisting = 0;

for (const n of niches) {
  if (existing.has(n.slug)) {
    skippedExisting++;
    continue;
  }
  const kw = `thiết kế website ${n.label.toLowerCase()}`;
  const h1 = `Thiết Kế Website ${titleCaseVi(n.label)} Chuyên Nghiệp Chuẩn SEO`;
  keywords.push({
    slug: n.slug,
    keywordsMain: kw,
    h1,
    angle: `website ngành ${n.label.toLowerCase()} tăng lead, SEO local và chuyển đổi`,
    niche: "strategy",
  });
  industries.push({
    title: h1,
    slug: n.slug,
    h1,
    keywordsMain: "thiết kế website",
    keywordsSecondary: `${kw}, website ${n.label.toLowerCase()}, làm web ${n.label.toLowerCase()}`,
    industry: n.label.toLowerCase(),
    niche: n.label.toLowerCase(),
    features: [
      `Trang dịch vụ / sản phẩm phù hợp ngành ${n.label.toLowerCase()}`,
      "Form báo giá / liên hệ Zalo trên mobile",
      "Gallery hoặc catalog minh họa thực tế",
      "SEO on-page từ khóa ngành + khu vực",
      "Blog giáo dục khách hàng hỗ trợ silo SEO",
    ],
    faq: [
      {
        q: `Website ${n.label.toLowerCase()} cần những trang nào?`,
        a: "Thường gồm trang chủ, dịch vụ/sản phẩm, báo giá hoặc bảng giá, giới thiệu, liên hệ và blog SEO.",
      },
      {
        q: `Giá thiết kế website ${n.label.toLowerCase()} khoảng bao nhiêu?`,
        a: "Gói Bứt Phá từ 3–12 triệu tùy số trang, mockup và tích hợp form/Zalo/SEO.",
      },
      {
        q: `Có tối ưu Google Maps không?`,
        a: "Có. Kết hợp schema LocalBusiness, NAP đồng nhất và liên kết Google Business Profile.",
      },
    ],
  });
}

function dumpArray(name, rows, indent = 2) {
  const sp = " ".repeat(indent);
  const body = rows
    .map((row) => {
      return `${sp}${JSON.stringify(row, null, indent).replace(/\n/g, `\n${sp}`)}`;
    })
    .join(",\n");
  return `export const ${name} = [\n${body}\n];\n`;
}

fs.writeFileSync(
  outKw,
  `/** AUTO-GENERATED by scripts/_gen-niche-500.mjs — ${keywords.length} từ khóa ngành ngách */\n` +
    dumpArray("NICHE_500_KEYWORDS", keywords),
  "utf8",
);

fs.writeFileSync(
  outInd,
  `/** AUTO-GENERATED by scripts/_gen-niche-500.mjs — ${industries.length} IndustryEntry */\n` +
    dumpArray("NICHE_500_INDUSTRY_ENTRIES", industries),
  "utf8",
);

console.log(`Parsed niches: ${niches.length}`);
console.log(`Skip existing INDUSTRY_ENTRIES: ${skippedExisting}`);
console.log(`Keywords written: ${keywords.length} → ${outKw}`);
console.log(`Industry entries: ${industries.length} → ${outInd}`);
