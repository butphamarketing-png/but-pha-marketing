/**
 * Gen keyword + industry từ batch2 (500) + batch3 (2000).
 * Chạy: node scripts/_gen-niche-batch23.mjs
 */
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const sources = [
  path.join(root, "tmp-programmatic", "nganh-nghe-500-batch2.json"),
  path.join(root, "tmp-programmatic", "nganh-nghe-2000-batch3.json"),
];
const outKw = path.join(root, "scripts", "seo-niche-batch23-keywords.mjs");
const outInd = path.join(root, "scripts", "seo-niche-batch23-industry.mjs");

const existingFiles = [
  path.join(root, "scripts", "seo-industry-data.mjs"),
  path.join(root, "scripts", "seo-niche-500-keywords.mjs"),
  path.join(root, "scripts", "seo-niche-1000-keywords.mjs"),
];
const existing = new Set();
for (const f of existingFiles) {
  if (!fs.existsSync(f)) continue;
  const src = fs.readFileSync(f, "utf8");
  for (const m of src.matchAll(/"slug":\s*"([^"]+)"/g)) {
    if (m[1].startsWith("thiet-ke-website-")) existing.add(m[1]);
  }
  for (const m of src.matchAll(/slug:\s*"([^"]+)"/g)) {
    if (m[1].startsWith("thiet-ke-website-")) existing.add(m[1]);
  }
}

function titleCaseVi(s) {
  return s
    .split(" ")
    .map((w) => (w ? w[0].toUpperCase() + w.slice(1) : w))
    .join(" ");
}

const keywords = [];
const industries = [];
let skipped = 0;

for (const srcPath of sources) {
  const { niches } = JSON.parse(fs.readFileSync(srcPath, "utf8"));
  for (const n of niches) {
    const slug = n.blogSlug || `thiet-ke-website-${n.slug}`;
    if (existing.has(slug)) {
      skipped++;
      continue;
    }
    existing.add(slug);
    const label = n.label;
    const labelLower = label.toLowerCase();
    const kw = n.kw || `thiết kế website ${labelLower}`;
    const h1 = `Thiết Kế Website ${titleCaseVi(label)} Chuyên Nghiệp Chuẩn SEO`;
    keywords.push({
      slug,
      keywordsMain: kw,
      h1,
      angle: `website ngành ${labelLower} tăng lead, SEO local và chuyển đổi`,
      niche: "strategy",
    });
    industries.push({
      title: h1,
      slug,
      h1,
      keywordsMain: "thiết kế website",
      keywordsSecondary: `${kw}, website ${labelLower}, làm web ${labelLower}`,
      industry: labelLower,
      niche: labelLower,
      features: [
        `Trang dịch vụ / sản phẩm phù hợp ngành ${labelLower}`,
        "Form báo giá / liên hệ Zalo trên mobile",
        "Gallery hoặc catalog minh họa thực tế",
        "SEO on-page từ khóa ngành + khu vực",
        "Blog giáo dục khách hàng hỗ trợ silo SEO",
      ],
      faq: [
        {
          q: `Website ${labelLower} cần những trang nào?`,
          a: "Thường gồm trang chủ, dịch vụ/sản phẩm, báo giá hoặc bảng giá, giới thiệu, liên hệ và blog SEO.",
        },
        {
          q: `Giá thiết kế website ${labelLower} khoảng bao nhiêu?`,
          a: "Gói Bứt Phá từ 3–12 triệu tùy số trang, mockup và tích hợp form/Zalo/SEO.",
        },
        {
          q: `Có tối ưu Google Maps không?`,
          a: "Có. Kết hợp schema LocalBusiness, NAP đồng nhất và liên kết Google Business Profile.",
        },
      ],
    });
  }
}

function dumpArray(name, rows, indent = 2) {
  const sp = " ".repeat(indent);
  const body = rows
    .map((row) => `${sp}${JSON.stringify(row, null, indent).replace(/\n/g, `\n${sp}`)}`)
    .join(",\n");
  return `export const ${name} = [\n${body}\n];\n`;
}

fs.writeFileSync(
  outKw,
  `/** AUTO-GENERATED by scripts/_gen-niche-batch23.mjs — ${keywords.length} từ khóa */\n` +
    dumpArray("NICHE_BATCH23_KEYWORDS", keywords),
  "utf8",
);
fs.writeFileSync(
  outInd,
  `/** AUTO-GENERATED by scripts/_gen-niche-batch23.mjs — ${industries.length} IndustryEntry */\n` +
    dumpArray("NICHE_BATCH23_INDUSTRY_ENTRIES", industries),
  "utf8",
);

console.log(`Skip existing: ${skipped}`);
console.log(`Keywords: ${keywords.length} → ${outKw}`);
console.log(`Industries: ${industries.length} → ${outInd}`);
