/**
 * Từ tu-khoa-khach-hang-1000.json → keyword seed catalog (skip slug đã có).
 * Chạy: node scripts/_gen-customer-kw-1000.mjs
 */
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const jsonPath = path.join(root, "tmp-programmatic", "tu-khoa-khach-hang-1000.json");
const outKw = path.join(root, "scripts", "seo-customer-keywords-1000.mjs");

const existingFiles = [
  "seo-industry-data.mjs",
  "seo-niche-500-keywords.mjs",
  "seo-niche-1000-keywords.mjs",
  "seo-niche-batch23-keywords.mjs",
  "seo-customer-keywords-100.mjs",
].map((f) => path.join(root, "scripts", f));

const existing = new Set();
for (const f of existingFiles) {
  if (!fs.existsSync(f)) continue;
  const src = fs.readFileSync(f, "utf8");
  for (const m of src.matchAll(/"slug":\s*"([^"]+)"/g)) existing.add(m[1]);
  for (const m of src.matchAll(/slug:\s*"([^"]+)"/g)) existing.add(m[1]);
}

function titleCaseVi(s) {
  return s
    .split(" ")
    .map((w) => (w ? w[0].toUpperCase() + w.slice(1) : w))
    .join(" ");
}

const { keywords: rows } = JSON.parse(fs.readFileSync(jsonPath, "utf8"));
const keywords = [];
let skipped = 0;
const usedSlug = new Set(existing);

for (const r of rows) {
  let slug = r.slug;
  if (usedSlug.has(slug)) {
    // disambiguate customer-intent slug
    const alt = `${slug}-kh`;
    if (usedSlug.has(alt)) {
      skipped++;
      continue;
    }
    slug = alt;
  }
  usedSlug.add(slug);

  const kw = r.kw;
  const h1 =
    r.intent === "transactional"
      ? `${titleCaseVi(kw)} — Báo Giá & Tư Vấn Nhanh`
      : r.intent === "informational"
        ? `${titleCaseVi(kw)} — Giải Đáp Chi Tiết`
        : `${titleCaseVi(kw)} — Giải Pháp Thực Chiến`;

  keywords.push({
    slug,
    keywordsMain: kw,
    h1,
    angle: `${kw}: hướng dẫn và giải pháp từ Bứt Phá Marketing`,
    niche: r.group || "strategy",
    intent: r.intent || "commercial",
  });
}

function dumpArray(name, rowsOut, indent = 2) {
  const sp = " ".repeat(indent);
  const body = rowsOut
    .map((row) => `${sp}${JSON.stringify(row, null, indent).replace(/\n/g, `\n${sp}`)}`)
    .join(",\n");
  return `export const ${name} = [\n${body}\n];\n`;
}

fs.writeFileSync(
  outKw,
  `/** AUTO-GENERATED by scripts/_gen-customer-kw-1000.mjs — ${keywords.length} KW khách hàng */\n` +
    dumpArray("CUSTOMER_KEYWORDS_1000", keywords),
  "utf8",
);

console.log(`Input: ${rows.length} | Skip: ${skipped} | Written: ${keywords.length}`);
console.log(outKw);
