import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, "..");

const DEFAULT_CONFIG_PATH = path.join(root, "scripts", "programmatic-landings.config.json");
const DEFAULT_OUT_DIR = path.join(root, "tmp-programmatic");
const GENERATED_MODULE_PATH = path.join(root, "lib", "programmatic-seo.generated.ts");
const INDEX_THRESHOLD = 70;

function getArg(flag, fallback = undefined) {
  const idx = process.argv.indexOf(flag);
  if (idx === -1) return fallback;
  return process.argv[idx + 1] ?? fallback;
}

function hasFlag(flag) {
  return process.argv.includes(flag);
}

function ensureDir(targetPath) {
  fs.mkdirSync(targetPath, { recursive: true });
}

function clamp(n, min, max) {
  return Math.max(min, Math.min(max, n));
}

function scoreLanding(input) {
  let score = 0;
  score += clamp(Math.round((input.wordCount || 0) / 200), 0, 10) * 3; // max 30
  score += clamp(input.faqCount || 0, 0, 6) * 3; // max 18
  score += clamp(input.internalLinkCount || 0, 0, 12) * 2; // max 24
  score += clamp(input.proofCount || 0, 0, 4) * 4; // max 16
  if (input.hasCaseStudy) score += 6;
  if (input.hasLocalEntity) score += 4;

  const duplicatePenalty = input.duplicateRisk === "high" ? 12 : input.duplicateRisk === "medium" ? 6 : 0;
  score -= duplicatePenalty;

  return clamp(score, 0, 100);
}

function resolveIndexPolicy(input, qualityScore) {
  if (input.indexOverride === "index" || input.indexOverride === "noindex") return input.indexOverride;
  return qualityScore >= INDEX_THRESHOLD ? "index" : "noindex";
}

function toOutputRow(type, item) {
  const qualityScore = scoreLanding(item);
  const indexPolicy = resolveIndexPolicy(item, qualityScore);
  const routePath =
    type === "websiteIndustry" ? `/website/nganh/${item.slug}` : `/seo-website/dia-phuong/${item.slug}`;

  return {
    type,
    slug: item.slug,
    title: item.title,
    description: item.description,
    primaryKeyword: item.primaryKeyword,
    qualityScore,
    indexPolicy,
    routePath,
    indexOverride: item.indexOverride || null,
    checklist: {
      wordCount: item.wordCount || 0,
      faqCount: item.faqCount || 0,
      internalLinkCount: item.internalLinkCount || 0,
      proofCount: item.proofCount || 0,
      hasCaseStudy: Boolean(item.hasCaseStudy),
      hasLocalEntity: Boolean(item.hasLocalEntity),
      duplicateRisk: item.duplicateRisk || "unknown",
    },
  };
}

function renderModule(rows) {
  const website = rows.filter((r) => r.type === "websiteIndustry");
  const local = rows.filter((r) => r.type === "localSeo");
  const toLiteral = (entry) => `{
    slug: "${entry.slug}",
    title: ${JSON.stringify(entry.title)},
    description: ${JSON.stringify(entry.description)},
    primaryKeyword: ${JSON.stringify(entry.primaryKeyword)},
    qualityScore: ${entry.qualityScore}
  }`;

  return `/* eslint-disable */
// AUTO-GENERATED by scripts/seed-programmatic-landings.mjs
// Do not edit manually.

export type ProgrammaticGeneratedLanding = {
  slug: string;
  title: string;
  description: string;
  primaryKeyword: string;
  qualityScore: number;
};

export const WEBSITE_INDUSTRY_GENERATED: ProgrammaticGeneratedLanding[] = [
${website.map((x) => `  ${toLiteral(x)},`).join("\n")}
];

export const LOCAL_SEO_GENERATED: ProgrammaticGeneratedLanding[] = [
${local.map((x) => `  ${toLiteral(x)},`).join("\n")}
];
`;
}

function renderMarkdown(rows) {
  const total = rows.length;
  const indexable = rows.filter((r) => r.indexPolicy === "index").length;
  const noindex = total - indexable;
  const lines = [];

  lines.push("# Programmatic Landing Quality Report");
  lines.push("");
  lines.push(`- Total: **${total}**`);
  lines.push(`- Index: **${indexable}**`);
  lines.push(`- Noindex: **${noindex}**`);
  lines.push(`- Threshold: **${INDEX_THRESHOLD}**`);
  lines.push("");

  for (const row of rows) {
    lines.push(`## ${row.routePath}`);
    lines.push(`- Title: ${row.title}`);
    lines.push(`- Keyword: ${row.primaryKeyword}`);
    lines.push(`- Quality: ${row.qualityScore}/100`);
    lines.push(`- Policy: ${row.indexPolicy}`);
    lines.push(
      `- Checklist: words=${row.checklist.wordCount}, faq=${row.checklist.faqCount}, links=${row.checklist.internalLinkCount}, proof=${row.checklist.proofCount}, caseStudy=${row.checklist.hasCaseStudy}, localEntity=${row.checklist.hasLocalEntity}, duplicateRisk=${row.checklist.duplicateRisk}`,
    );
    lines.push("");
  }

  return lines.join("\n");
}

function main() {
  const configPath = path.resolve(getArg("--config", DEFAULT_CONFIG_PATH));
  const outDir = path.resolve(getArg("--outDir", DEFAULT_OUT_DIR));
  const writeModule = hasFlag("--write-module");

  if (!fs.existsSync(configPath)) {
    console.error(`Config not found: ${configPath}`);
    process.exit(1);
  }

  const raw = fs.readFileSync(configPath, "utf8");
  const parsed = JSON.parse(raw);
  const websiteIndustry = Array.isArray(parsed.websiteIndustry) ? parsed.websiteIndustry : [];
  const localSeo = Array.isArray(parsed.localSeo) ? parsed.localSeo : [];
  const rows = [
    ...websiteIndustry.map((x) => toOutputRow("websiteIndustry", x)),
    ...localSeo.map((x) => toOutputRow("localSeo", x)),
  ];

  ensureDir(outDir);
  const reportJsonPath = path.join(outDir, "programmatic-quality-report.json");
  const reportMdPath = path.join(outDir, "programmatic-quality-report.md");
  const indexablePath = path.join(outDir, "programmatic-indexable-paths.txt");

  fs.writeFileSync(reportJsonPath, JSON.stringify(rows, null, 2), "utf8");
  fs.writeFileSync(reportMdPath, renderMarkdown(rows), "utf8");
  fs.writeFileSync(
    indexablePath,
    rows
      .filter((r) => r.indexPolicy === "index")
      .map((r) => r.routePath)
      .join("\n"),
    "utf8",
  );

  if (writeModule) {
    fs.writeFileSync(GENERATED_MODULE_PATH, renderModule(rows), "utf8");
  }

  const indexCount = rows.filter((r) => r.indexPolicy === "index").length;
  console.log("=== Programmatic landing seed prepared ===");
  console.log(`Config: ${configPath}`);
  console.log(`Output: ${outDir}`);
  console.log(`Total rows: ${rows.length}`);
  console.log(`Indexable: ${indexCount}`);
  console.log(`Noindex: ${rows.length - indexCount}`);
  if (writeModule) console.log(`Generated module: ${GENERATED_MODULE_PATH}`);
}

main();
