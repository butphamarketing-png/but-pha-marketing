/**
 * Từ tu-khoa-nganh-nghe-1000.json → keyword + industry (chỉ niche chưa có trong INDUSTRY_ENTRIES).
 * Chạy: node scripts/_gen-niche-1000.mjs
 */
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const jsonPath = path.join(root, "tmp-programmatic", "tu-khoa-nganh-nghe-1000.json");
const outKw = path.join(root, "scripts", "seo-niche-1000-keywords.mjs");
const outInd = path.join(root, "scripts", "seo-niche-1000-industry.mjs");
const industryDataPath = path.join(root, "scripts", "seo-industry-data.mjs");
const niche500Kw = path.join(root, "scripts", "seo-niche-500-keywords.mjs");

const industrySrc = fs.readFileSync(industryDataPath, "utf8");
const niche500Src = fs.readFileSync(niche500Kw, "utf8");
const existing = new Set([
  ...[...industrySrc.matchAll(/slug:\s*"([^"]+)"/g)].map((m) => m[1]),
  ...[...niche500Src.matchAll(/"slug":\s*"([^"]+)"/g)].map((m) => m[1]),
].filter((s) => s.startsWith("thiet-ke-website-")));

const { keywords: rows } = JSON.parse(fs.readFileSync(jsonPath, "utf8"));

function titleCaseVi(s) {
  return s
    .split(" ")
    .map((w) => (w ? w[0].toUpperCase() + w.slice(1) : w))
    .join(" ");
}

const keywords = [];
const industries = [];
let skippedExisting = 0;

for (const r of rows) {
  const slug = r.slug;
  if (existing.has(slug)) {
    skippedExisting++;
    continue;
  }
  const label = r.label;
  const labelLower = label.toLowerCase();
  const kw = r.kw || `thiết kế website ${labelLower}`;
  const h1 = `Thiết Kế Website ${titleCaseVi(label)} Chuyên Nghiệp Chuẩn SEO`;
  keywords.push({
    slug,
    keywordsMain: kw,
    h1,
    angle: `website ngành ${labelLower} tăng lead, SEO local và chuyển đổi`,
    niche: "strategy",
  });
  industries.push({
    title: h1,
    slug,
    h1,
    keywordsMain: "thiết kế website",
    keywordsSecondary: `${kw}, website ${labelLower}, làm web ${labelLower}`,
    industry: labelLower,
    niche: labelLower,
    features: [
      `Trang dịch vụ / sản phẩm phù hợp ngành ${labelLower}`,
      "Form báo giá / liên hệ Zalo trên mobile",
      "Gallery hoặc catalog minh họa thực tế",
      "SEO on-page từ khóa ngành + khu vực",
      "Blog giáo dục khách hàng hỗ trợ silo SEO",
    ],
    faq: [
      {
        q: `Website ${labelLower} cần những trang nào?`,
        a: "Thường gồm trang chủ, dịch vụ/sản phẩm, báo giá hoặc bảng giá, giới thiệu, liên hệ và blog SEO.",
      },
      {
        q: `Giá thiết kế website ${labelLower} khoảng bao nhiêu?`,
        a: "Gói Bứt Phá từ 3–12 triệu tùy số trang, mockup và tích hợp form/Zalo/SEO.",
      },
      {
        q: `Có tối ưu Google Maps không?`,
        a: "Có. Kết hợp schema LocalBusiness, NAP đồng nhất và liên kết Google Business Profile.",
      },
    ],
  });
}

function dumpArray(name, rowsOut, indent = 2) {
  const sp = " ".repeat(indent);
  const body = rowsOut
    .map((row) => `${sp}${JSON.stringify(row, null, indent).replace(/\n/g, `\n${sp}`)}`)
    .join(",\n");
  return `export const ${name} = [\n${body}\n];\n`;
}

fs.writeFileSync(
  outKw,
  `/** AUTO-GENERATED by scripts/_gen-niche-1000.mjs — ${keywords.length} từ khóa ngành batch 1000 */\n` +
    dumpArray("NICHE_1000_KEYWORDS", keywords),
  "utf8",
);
fs.writeFileSync(
  outInd,
  `/** AUTO-GENERATED by scripts/_gen-niche-1000.mjs — ${industries.length} IndustryEntry */\n` +
    dumpArray("NICHE_1000_INDUSTRY_ENTRIES", industries),
  "utf8",
);

console.log(`Catalog 1000 rows: ${rows.length}`);
console.log(`Skip existing: ${skippedExisting}`);
console.log(`New keywords: ${keywords.length} → ${outKw}`);
console.log(`New industries: ${industries.length} → ${outInd}`);
