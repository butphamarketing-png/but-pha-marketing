/**
 * Quét kích thước mockup trong public/tin-tuc → lib/industry-mockup-dimensions.generated.ts
 * Chạy: node scripts/audit-industry-mockup-dimensions.mjs
 */
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const publicRoot = path.join(root, "public", "tin-tuc");
const outPath = path.join(root, "lib", "industry-mockup-dimensions.generated.ts");

function pngSize(buf) {
  if (buf.length < 24 || buf[0] !== 0x89) return null;
  return { width: buf.readUInt32BE(16), height: buf.readUInt32BE(20) };
}

function jpegSize(buf) {
  let i = 2;
  while (i < buf.length - 8) {
    if (buf[i] !== 0xff) break;
    const marker = buf[i + 1];
    const len = buf.readUInt16BE(i + 2);
    if (marker >= 0xc0 && marker <= 0xcf && marker !== 0xc4 && marker !== 0xc8) {
      return { width: buf.readUInt16BE(i + 7), height: buf.readUInt16BE(i + 5) };
    }
    i += 2 + len;
  }
  return null;
}

function readDimensions(filePath) {
  const buf = fs.readFileSync(filePath);
  return pngSize(buf) ?? jpegSize(buf);
}

function walk(dir, relPrefix, out) {
  for (const ent of fs.readdirSync(dir, { withFileTypes: true })) {
    const abs = path.join(dir, ent.name);
    const rel = relPrefix ? `${relPrefix}/${ent.name}` : ent.name;
    if (ent.isDirectory()) {
      walk(abs, rel, out);
      continue;
    }
    if (!/\.(png|jpe?g)$/i.test(ent.name)) continue;
    const dims = readDimensions(abs);
    if (!dims) continue;
    out[`/tin-tuc/${rel.replace(/\\/g, "/")}`] = dims;
  }
}

const dimensions = {};
walk(publicRoot, "", dimensions);

const lines = [];
lines.push("/* eslint-disable */");
lines.push("// AUTO-GENERATED by scripts/audit-industry-mockup-dimensions.mjs");
lines.push("// Do not edit manually.");
lines.push("");
lines.push("export type MockupDimensions = { width: number; height: number };");
lines.push("");
lines.push("export const INDUSTRY_MOCKUP_DIMENSIONS: Record<string, MockupDimensions> = {");
for (const [src, dims] of Object.entries(dimensions).sort(([a], [b]) => a.localeCompare(b))) {
  lines.push(`  ${JSON.stringify(src)}: { width: ${dims.width}, height: ${dims.height} },`);
}
lines.push("};");
lines.push("");
lines.push(`export const INDUSTRY_MOCKUP_HD_TARGET = 1920;`);
lines.push("");
lines.push("export function getMockupDimensions(src: string): MockupDimensions | null {");
lines.push("  return INDUSTRY_MOCKUP_DIMENSIONS[src] ?? null;");
lines.push("}");
lines.push("");
lines.push("export function mockupDisplayWidth(src: string, fallback = 485): number {");
lines.push("  const d = getMockupDimensions(src);");
lines.push("  if (!d) return fallback;");
lines.push("  return Math.min(d.width, INDUSTRY_MOCKUP_HD_TARGET);");
lines.push("}");
lines.push("");
lines.push("export function hdMockupVariantSrc(src: string): string | null {");
lines.push("  const m = src.match(/^(\/tin-tuc\\/.*\\/)([^/]+)\\.(png|jpe?g)$/i);");
lines.push("  if (!m) return null;");
lines.push("  const base = m[2].replace(/\\.(png|jpe?g)$/i, \"\");");
lines.push("  return `${m[1]}hd/${base}-1920.webp`;");
lines.push("}");

fs.writeFileSync(outPath, lines.join("\n"), "utf8");

const values = Object.values(dimensions);
const under800 = values.filter((d) => d.width < 800).length;
const at1536 = values.filter((d) => d.width >= 1536).length;
console.log("=== Industry mockup dimension audit ===");
console.log(`Scanned: ${values.length} images`);
console.log(`Under 800px wide: ${under800}`);
console.log(`At/above 1536px: ${at1536}`);
console.log(`Generated: ${outPath}`);
