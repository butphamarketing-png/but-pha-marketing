import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const existing = JSON.parse(
  fs.readFileSync(path.join(root, "tmp-programmatic", "_existing-slugs-kws.json"), "utf8"),
);
const existingSlugs = new Set(existing.slugs);
const existingKws = new Set(existing.kws.map((k) => k.toLowerCase()));

function slugify(s) {
  return String(s)
    .toLowerCase()
    .normalize("NFD")
    .replace(/\p{M}/gu, "")
    .replace(/đ/g, "d")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "")
    .replace(/-+/g, "-");
}

function titleCase(s) {
  return String(s)
    .trim()
    .split(/\s+/)
    .map((w) => {
      const up = ["ai", "seo", "geo", "llm", "gpt", "api", "crm", "roi", "cpa", "roas", "ugc", "sme", "b2b", "b2c", "oa", "faq", "cro"];
      const bare = w.normalize("NFD").replace(/\p{M}/gu, "").toLowerCase();
      if (up.includes(bare) && !/[àáạảãâăèéêìíòóôơùúýđ]/i.test(w)) return bare.toUpperCase();
      return w.charAt(0).toUpperCase() + w.slice(1);
    })
    .join(" ");
}

const entries = [];
const usedSlugs = new Set();
const usedKws = new Set();

function add(kw, h1, angle, niche, intent, slugExtra = "") {
  const keywordsMain = kw.trim();
  const key = keywordsMain.toLowerCase();
  if (usedKws.has(key) || existingKws.has(key)) return false;

  let base = slugify(keywordsMain) + (slugExtra || "-b23");
  let slug = base;
  let n = 2;
  while (usedSlugs.has(slug) || existingSlugs.has(slug)) {
    slug = `${base}-${n++}`;
  }

  usedKws.add(key);
  usedSlugs.add(slug);
  entries.push({
    slug,
    keywordsMain,
    h1: h1.includes("?") || h1.includes("—") ? h1 : `${titleCase(h1)}`,
    angle,
    niche,
    intent,
  });
  return true;
}

function addMany(list) {
  for (const row of list) add(...row);
}

