function parseMd500(text) {
  return [...text.matchAll(/^\d+\.\s+(.+?)\s+—\s+`([^`]+)`/gm)].map((m) => ({
    label: m[1].replace(/\s+/g, " ").trim(),
    slug: m[2].trim(),
  }));
}

const from500 = parseMd500(fs.readFileSync(md500, "utf8"));
const extra = EXTRA_500.map(([label, slug]) => ({ label, slug }));

const seenSlug = new Set();
const niches = [];
for (const n of [...from500, ...extra]) {
  if (seenSlug.has(n.slug)) continue;
  seenSlug.add(n.slug);
  niches.push(n);
}

const TARGET = 1000;
const rows = niches.slice(0, TARGET).map((n, i) => ({
  n: i + 1,
  kw: `thiết kế website ${n.label.toLowerCase()}`,
  slug: `thiet-ke-website-${n.slug}`,
  label: n.label,
}));

// pad if short
while (rows.length < TARGET && extra.length) {
  break;
}

const lines = [];
lines.push("# 1000 từ khóa ngành nghề — thiết kế website + ngành");
lines.push("");
lines.push(`- Generated: ${new Date().toISOString()}`);
lines.push(`- Tổng: **${rows.length}** từ khóa`);
lines.push(`- Nguồn: 500 ngành gốc + ${extra.length} ngành bổ sung`);
lines.push("");
lines.push("| # | Từ khóa | Slug |");
lines.push("|---|---------|------|");
for (const r of rows) {
  lines.push(`| ${r.n} | ${r.kw} | \`${r.slug}\` |`);
}
lines.push("");

fs.writeFileSync(outMd, lines.join("\n"), "utf8");
fs.writeFileSync(
  outJson,
  JSON.stringify({ generatedAt: new Date().toISOString(), total: rows.length, keywords: rows }, null, 2),
  "utf8",
);

